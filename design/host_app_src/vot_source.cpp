bool manifest_parse(const char *text, size_t len, Manifest &m, std::string &err)
{
    std::string owned(text, len);          // guarantees the NUL strtod relies on
    Parser ps;
    ps.base = owned.c_str();
    ps.p    = owned.c_str();
    ps.end  = owned.c_str() + owned.size();

    Value root;
    if (!ps.value(root)) { err = ps.err; return false; }
    if (root.type != Value::Obj) { err = "manifest root is not an object"; return false; }

    m = Manifest{};
    if (!int_field(root, "schema",      m.schema,      err)) return false;
    if (!str_field(root, "sequence",    m.sequence,    err)) return false;
    if (!int_field(root, "frames",      m.frames,      err)) return false;
    if (!int_field(root, "rows",        m.rows,        err)) return false;
    if (!int_field(root, "cols",        m.cols,        err)) return false;
    if (!int_field(root, "channels",    m.channels,    err)) return false;
    if (!str_field(root, "blob",        m.blob,        err)) return false;
    if (!str_field(root, "blob_md5",    m.blob_md5,    err)) return false;
    if (!str_field(root, "gt_format",   m.gt_format,   err)) return false;
    if (!str_field(root, "anchors_source", m.anchors_source, err)) return false;
    if (!int_field(root, "empty_boxes", m.empty_boxes, err)) return false;
    if (!int_field(root, "roi_exceeds_frame", m.roi_exceeds_frame, err)) return false;
    if (!num_field(root, "min_box_side", m.min_box_side, err)) return false;

    // frame_bytes is CARRIED, not derived, and then cross-checked below. The
    // manifest is the authority on its own layout; recomputing it here would be a
    // second implementation of the rule, which is the shape of bug Phase 1 found
    // in reduce_box (two copies of one wrong rule agreeing with each other).
    {
        double fb = 0.0;
        if (!num_field(root, "frame_bytes", fb, err)) return false;
        if (fb <= 0.0 || fb != std::floor(fb)) { err = "frame_bytes is not a positive integer"; return false; }
        m.frame_bytes = (size_t)fb;
    }

    const Value *lb = root.find("luma_blob");
    if (lb && lb->type == Value::Str) m.luma_blob = lb->str;   // null at channels=1

    if (m.schema != 1) {
        char buf[96];
        snprintf(buf, sizeof buf, "manifest schema %d, this build understands 1", m.schema);
        err = buf;
        return false;
    }
    if (m.rows <= 0 || m.cols <= 0 || m.frames <= 0) { err = "degenerate geometry"; return false; }
    if (m.channels != 1 && m.channels != 3) { err = "channels must be 1 or 3"; return false; }
    if (m.frame_bytes != (size_t)m.rows * m.cols * m.channels) {
        err = "frame_bytes disagrees with rows*cols*channels";
        return false;
    }

    const Value *gt = nullptr;
    if (!need(root, "groundtruth", Value::Arr, &gt, err)) return false;
    if ((int)gt->arr.size() != m.frames) { err = "groundtruth length != frames"; return false; }
    m.groundtruth.resize(gt->arr.size());
    for (size_t i = 0; i < gt->arr.size(); ++i)
        if (!box_from(gt->arr[i], m.groundtruth[i], "groundtruth", err)) return false;

    const Value *jobs = nullptr;
    if (!need(root, "jobs", Value::Arr, &jobs, err)) return false;
    m.jobs.reserve(jobs->arr.size());
    for (const Value &jv : jobs->arr) {
        if (jv.type != Value::Obj) { err = "job is not an object"; return false; }
        Job j;
        if (!int_field(jv, "anchor", j.anchor, err)) return false;
        if (!int_field(jv, "length", j.length, err)) return false;
        std::string dir;
        if (!str_field(jv, "direction", dir, err)) return false;
        if (dir == "forward")       j.forward = true;
        else if (dir == "backward") j.forward = false;
        else { err = "job direction is neither forward nor backward"; return false; }
        const Value *ib = jv.find("init_box");
        if (!ib || !box_from(*ib, j.init_box, "init_box", err)) {
            if (err.empty()) err = "job is missing init_box";
            return false;
        }
        if (j.anchor < 0 || j.anchor >= m.frames) { err = "job anchor out of range"; return false; }
        // Derivable, and CHECKED rather than derived — a length that disagrees
        // with the anchor means the manifest and the direction convention have
        // drifted apart, and that is exactly the failure that reads as "a tracker
        // that runs backwards" rather than as an error.
        const int expect = j.forward ? (m.frames - j.anchor) : (j.anchor + 1);
        if (j.length != expect) { err = "job length disagrees with anchor and direction"; return false; }
        m.jobs.push_back(j);
    }
    if (m.jobs.empty()) { err = "manifest has no jobs"; return false; }
    return true;
}

bool manifest_load(const std::string &path, Manifest &m, std::string &err)
{
    FILE *f = fopen(path.c_str(), "rb");
    if (!f) { err = "cannot open " + path + ": " + strerror(errno); return false; }
    std::string text;
    char buf[65536];
    size_t n;
    while ((n = fread(buf, 1, sizeof buf, f)) > 0) text.append(buf, n);
    const bool bad = ferror(f) != 0;
    fclose(f);
    if (bad) { err = "read error on " + path; return false; }
    if (text.empty()) { err = path + " is empty"; return false; }
    return manifest_parse(text.data(), text.size(), m, err);
}

// ---------------------------------------------------------------------------
// The two loaders differ ONLY in frame size, so they share one reader rather
// than carrying two copies of the short-read / long-blob checks. A second copy
// of those checks is a second thing to get wrong, and the failure they catch --
// a blob and a manifest disagreeing about geometry -- is silent in exactly the
// way that makes every later frame offset a guess.
bool Blob::load_sized(const std::string &path, size_t fb, int nframes,
                      std::string &err)
{
    const auto t0 = std::chrono::steady_clock::now();
    data_.clear();
    frame_bytes_ = 0;
    frames_ = 0;
    secs_ = 0.0;

    const size_t want = fb * (size_t)nframes;
    FILE *f = fopen(path.c_str(), "rb");
    if (!f) { err = "cannot open " + path + ": " + strerror(errno); return false; }

    // ONE sequential read into heap, sized from the manifest. The buffer is
    // allocated at exactly `want` and read in large chunks: peak heap is one
    // sequence (1269 MB for flamingo1, the largest in stb2022), against 12 GB.
    data_.resize(want);
    size_t got = 0;
    while (got < want) {
        const size_t n = fread(data_.data() + got, 1, want - got, f);
        if (n == 0) break;
        got += n;
    }
    // A byte PAST the expected end is as wrong as a byte short: it means the blob
    // and the manifest disagree about geometry or frame count, and every frame
    // offset after the first is then a guess.
    char extra;
    const bool longer = (fread(&extra, 1, 1, f) == 1);
    const bool bad = ferror(f) != 0;
    fclose(f);

    if (bad)    { data_.clear(); err = "read error on " + path; return false; }
    if (got != want || longer) {
        char b[192];
        snprintf(b, sizeof b, "%s: %zu bytes, manifest says %d frames x %zu = %zu",
                 path.c_str(), longer ? got + 1 : got, nframes, fb, want);
        data_.clear();
        err = b;
        return false;
    }

    frame_bytes_ = fb;
    frames_      = nframes;
    secs_ = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    return true;
}

bool Blob::load(const std::string &path, const Manifest &m, std::string &err)
{
    return load_sized(path, m.frame_bytes, m.frames, err);
}

bool Blob::load_luma(const std::string &path, const Manifest &m, std::string &err)
{
    // rows*cols, NOT m.frame_bytes: the sidecar is one plane whatever the blob's
    // channel count is. Taking m.frame_bytes here would read 3x the bytes, fail
    // the length check, and report it as a corrupt sidecar rather than as this
    // bug -- so the size is derived from the geometry, at the one site that
    // knows the sidecar is single-plane. That site is now luma_frame_bytes() in
    // the header, shared with StreamBlob::open_luma: this used to be the only
    // copy, and the streaming reader would have been the second.
    return load_sized(path, luma_frame_bytes(m), m.frames, err);
}

const uint8_t *Blob::frame(int i) const
{
    if (i < 0 || i >= frames_) return nullptr;
    return data_.data() + (size_t)i * frame_bytes_;
}

