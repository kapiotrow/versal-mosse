// ---------------------------------------------------------------------------
// A small strict JSON reader
// ---------------------------------------------------------------------------
// Hand-rolled rather than vendored because the board rootfs carries no JSON
// library and the input is machine-generated by one script in this repo. STRICT
// is the load-bearing word: every failure below returns an error with an offset,
// because the alternative — a lenient parser that silently yields a default —
// is how a manifest field ends up read as 0 and a whole run comes back plausible
// and wrong. It does not attempt \u escapes; the manifest has none, and a parser
// that pretends to handle something it does not is worse than one that says no.

struct Value {
    enum Type { Null, Bool, Num, Str, Arr, Obj } type = Null;
    bool        b = false;
    double      num = 0.0;
    std::string str;
    std::vector<Value> arr;
    std::vector<std::pair<std::string, Value>> obj;

    const Value *find(const char *key) const {
        if (type != Obj) return nullptr;
        for (const auto &kv : obj)
            if (kv.first == key) return &kv.second;
        return nullptr;
    }
};

struct Parser {
    const char *p, *end;
    std::string err;

    bool fail(const char *what) {
        char buf[128];
        snprintf(buf, sizeof buf, "%s at byte %ld", what, (long)(p - base));
        err = buf;
        return false;
    }
    const char *base;

    void ws() {
        while (p < end && (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')) ++p;
    }
    bool lit(const char *s) {
        size_t n = strlen(s);
        if ((size_t)(end - p) < n || memcmp(p, s, n) != 0) return false;
        p += n;
        return true;
    }
    bool value(Value &v);

    bool string(std::string &out) {
        if (p >= end || *p != '"') return fail("expected string");
        ++p;
        out.clear();
        while (p < end && *p != '"') {
            if (*p == '\\') {
                if (++p >= end) return fail("truncated escape");
                switch (*p) {
                    case '"':  out += '"';  break;
                    case '\\': out += '\\'; break;
                    case '/':  out += '/';  break;
                    case 'b':  out += '\b'; break;
                    case 'f':  out += '\f'; break;
                    case 'n':  out += '\n'; break;
                    case 'r':  out += '\r'; break;
                    case 't':  out += '\t'; break;
                    default:   return fail("unsupported escape");
                }
                ++p;
            } else {
                out += *p++;
            }
        }
        if (p >= end) return fail("unterminated string");
        ++p;
        return true;
    }
};

bool Parser::value(Value &v) {
    ws();
    if (p >= end) return fail("unexpected end of input");
    switch (*p) {
        case 'n': v.type = Value::Null; return lit("null") ? true : fail("expected null");
        case 't': v.type = Value::Bool; v.b = true;
                  return lit("true") ? true : fail("expected true");
        case 'f': v.type = Value::Bool; v.b = false;
                  return lit("false") ? true : fail("expected false");
        case '"': v.type = Value::Str;  return string(v.str);
        case '[': {
            v.type = Value::Arr;
            ++p; ws();
            if (p < end && *p == ']') { ++p; return true; }
            for (;;) {
                v.arr.emplace_back();
                if (!value(v.arr.back())) return false;
                ws();
                if (p < end && *p == ',') { ++p; continue; }
                if (p < end && *p == ']') { ++p; return true; }
                return fail("expected ',' or ']'");
            }
        }
        case '{': {
            v.type = Value::Obj;
            ++p; ws();
            if (p < end && *p == '}') { ++p; return true; }
            for (;;) {
                ws();
                std::string key;
                if (!string(key)) return false;
                ws();
                if (p >= end || *p != ':') return fail("expected ':'");
                ++p;
                v.obj.emplace_back(key, Value{});
                if (!value(v.obj.back().second)) return false;
                ws();
                if (p < end && *p == ',') { ++p; continue; }
                if (p < end && *p == '}') { ++p; return true; }
                return fail("expected ',' or '}'");
            }
        }
        default: {
            char *tail = nullptr;
            // The manifest is NUL-terminated by manifest_load/manifest_parse's
            // caller contract (both take a length and copy into a std::string),
            // so strtod cannot run off the end.
            double d = strtod(p, &tail);
            if (tail == p) return fail("expected a value");
            v.type = Value::Num;
            v.num  = d;
            p = tail;
            return true;
        }
    }
}

// ---------------------------------------------------------------------------
// typed field access — every one of these can FAIL, and says which key
// ---------------------------------------------------------------------------
bool need(const Value &o, const char *key, Value::Type t,
          const Value **out, std::string &err) {
    const Value *v = o.find(key);
    if (!v) { err = std::string("manifest is missing '") + key + "'"; return false; }
    if (v->type != t) { err = std::string("manifest key '") + key + "' has the wrong type"; return false; }
    *out = v;
    return true;
}

bool num_field(const Value &o, const char *key, double &dst, std::string &err) {
    const Value *v = nullptr;
    if (!need(o, key, Value::Num, &v, err)) return false;
    dst = v->num;
    return true;
}

bool int_field(const Value &o, const char *key, int &dst, std::string &err) {
    double d = 0.0;
    if (!num_field(o, key, d, err)) return false;
    if (d != std::floor(d)) { err = std::string("manifest key '") + key + "' is not an integer"; return false; }
    dst = (int)d;
    return true;
}

bool str_field(const Value &o, const char *key, std::string &dst, std::string &err) {
    const Value *v = nullptr;
    if (!need(o, key, Value::Str, &v, err)) return false;
    dst = v->str;
    return true;
}

// (row, col, h, w), the manifest's own order — vot_prepare.reduce_box emits
// centre-convention boxes, so this is a copy and not a conversion. If that ever
// changes it changes HERE and in reduce_box together, which is why the manifest
// spells the convention out in `gt_convention`.
bool box_from(const Value &v, Box &b, const char *what, std::string &err) {
    if (v.type != Value::Arr || v.arr.size() != 4) {
        err = std::string(what) + ": expected 4 numbers"; return false;
    }
    for (const Value &e : v.arr)
        if (e.type != Value::Num) { err = std::string(what) + ": non-numeric"; return false; }
    b.row = v.arr[0].num; b.col = v.arr[1].num;
    b.h   = v.arr[2].num; b.w   = v.arr[3].num;
    return true;
}

